class Layout:
    """Размеры окна и отступы."""

    # Стартовый размер главного окна «ширина x высота».
    WINDOW_SIZE = "940x820"
    # Минимальная ширина окна — меньше интерфейс начнёт «ломаться».
    MIN_WIDTH = 780
    # Минимальная высота окна.
    MIN_HEIGHT = 680
    # Внешний отступ от краёв окна до карточек.
    PAD_OUTER = 20
    # Внутренний отступ внутри карточек.
    PAD_INNER = 16
    # Радиус скругления углов карточек и кнопок.
    RADIUS = 12
    # Высота больших главных кнопок.
    BIG_BUTTON_HEIGHT = 52
    # Высота обычных кнопок.
    BUTTON_HEIGHT = 38


class Fonts:
    """Названия шрифтов (объекты CTkFont создаются в окне после запуска Tk)."""

    # На Windows используем системный шрифт Segoe UI, на других ОС — стандартный.
    UI_FAMILY = "Segoe UI" if sys.platform.startswith("win") else "Helvetica"
    # Моноширинный шрифт для лога: Consolas на Windows, Menlo/DejaVu на других ОС.
    MONO_FAMILY = (
        "Consolas" if sys.platform.startswith("win")
        else ("Menlo" if sys.platform == "darwin" else "DejaVu Sans Mono")
    )


class Behaviour:
    """Технические параметры поведения интерфейса."""

    # Как часто (в миллисекундах) окно забирает новые события из фонового потока.
    POLL_INTERVAL_MS = 60
    # Сколько событий максимум обрабатываем за один «тик», чтобы окно не подвисало.
    MAX_EVENTS_PER_TICK = 250
    # Максимум строк в логе — старые строки удаляются, чтобы не расходовать память.
    MAX_LOG_LINES = 5000


